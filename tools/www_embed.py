#!/usr/bin/env python3
"""Generates a C source with the web UI files from www/, gzipped, for the firmware to serve from flash.

Called by main/CMakeLists.txt on every change in www/. Each file becomes a const array, served with
Content-Encoding: gzip at "/<file name>". The ETag is the CRC32 of the gzipped data, so it only
changes when the file does.

Usage: tools/www_embed.py OUTPUT.c FILE...
"""

import gzip
import pathlib
import sys
import zlib

BYTES_PER_LINE = 16


def c_array(name, data):
    lines = []
    for i in range(0, len(data), BYTES_PER_LINE):
        lines.append('    ' + ', '.join(f'0x{b:02x}' for b in data[i:i + BYTES_PER_LINE]) + ',')
    return f'static const uint8_t {name}[] = {{\n' + '\n'.join(lines) + '\n};\n'


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)

    output = pathlib.Path(sys.argv[1])
    files = sorted((pathlib.Path(p) for p in sys.argv[2:] if pathlib.Path(p).is_file()), key=lambda p: p.name)

    arrays = []
    entries = []
    for i, path in enumerate(files):
        # mtime=0 keeps the output identical between builds of the same files
        data = gzip.compress(path.read_bytes(), compresslevel=9, mtime=0)
        arrays.append(c_array(f'file_{i}', data))
        entries.append(f'    {{"/{path.name}", file_{i}, sizeof(file_{i}), "\\"{zlib.crc32(data):08X}\\""}},')

    output.write_text(
            '// Generated by tools/www_embed.py from www/, do not edit\n\n'
            '#include <www_files.h>\n\n'
            + '\n'.join(arrays) + '\n'
            'const www_file_t www_files[] = {\n'
            + '\n'.join(entries) + '\n'
            '};\n\n'
            'const size_t www_files_count = sizeof(www_files) / sizeof(www_files[0]);\n')


if __name__ == '__main__':
    main()
