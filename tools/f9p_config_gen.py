#!/usr/bin/env python3
"""Generates main/f9p_config_data.h from the u-center ZED-F9P configuration dumps in tools/f9p/.

The dumps are u-center "Generation 9" configuration files: one CFG-VALGET response per line, as hex.
F9P_CFG_DUAL holds every key of the dual GPS config in file order, so the receiver is written in the
same 64 key groups u-center uses. F9P_CFG_RS232 holds only the keys whose value differs in the RS-232 config.

Usage: tools/f9p_config_gen.py [--check]
  --check  only compare against the existing header, exit 1 if it is out of date
"""

import argparse
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DUMPS = ROOT / 'tools' / 'f9p'
OUTPUT = ROOT / 'main' / 'f9p_config_data.h'

DUAL_FILE = 'F9P 1.13 DualGPS 10hz Nav-PVT right purple.txt'
RS232_FILE = 'F9P 1.13 Nav-PVT RS-232.txt'

EXPECTED_KEYS = 1212
EXPECTED_DIFFS = 24

# Value size in bytes from the key's size bits (28-30)
KEY_SIZES = {1: 1, 2: 1, 3: 2, 4: 4, 5: 8}


def parse(path):
    """Returns the firmware version and the (key, value) pairs in file order."""
    firmware = None
    items = []

    for line in path.read_text().splitlines():
        name, _, hex_bytes = line.partition(' - ')
        message = bytes(int(x, 16) for x in hex_bytes.split())
        length = message[2] | message[3] << 8
        payload = message[4:4 + length]

        if name.strip() == 'MON-VER':
            extensions = [payload[i:i + 30].split(b'\0')[0].decode() for i in range(40, len(payload), 30)]
            firmware = next((e[len('FWVER='):] for e in extensions if e.startswith('FWVER=')), None)
        elif name.strip() == 'CFG-VALGET':
            # version, layer, position, then key/value pairs
            i = 4
            while i < len(payload):
                key = int.from_bytes(payload[i:i + 4], 'little')
                size = KEY_SIZES[(key >> 28) & 7]
                value = int.from_bytes(payload[i + 4:i + 4 + size], 'little')
                items.append((key, value))
                i += 4 + size

    return firmware, items


def table(name, comment, items):
    lines = [f'// {comment}', f'static const f9p_cfg_item_t {name}[] = {{']
    for key, value in items:
        suffix = 'ull' if value > 0xFFFFFFFF else 'u'
        lines.append(f'        {{0x{key:08X}, {value}{suffix}}},')
    lines.append('};')
    return '\n'.join(lines)


def generate():
    dual_firmware, dual = parse(DUMPS / DUAL_FILE)
    rs232_firmware, rs232 = parse(DUMPS / RS232_FILE)

    if dual_firmware != rs232_firmware:
        sys.exit(f'Firmware differs: {dual_firmware} / {rs232_firmware}')
    if [k for k, _ in dual] != [k for k, _ in rs232]:
        sys.exit('Configs do not have the same keys in the same order')
    if len(dual) != EXPECTED_KEYS:
        sys.exit(f'Expected {EXPECTED_KEYS} keys, found {len(dual)}')

    rs232_changes = [r for d, r in zip(dual, rs232) if d != r]
    if len(rs232_changes) != EXPECTED_DIFFS:
        sys.exit(f'Expected {EXPECTED_DIFFS} differing keys, found {len(rs232_changes)}')

    return f'''// Generated by tools/f9p_config_gen.py from the u-center configuration dumps in tools/f9p/, do not edit.
// ZED-F9P firmware {dual_firmware}, {len(dual)} keys, {len(rs232_changes)} of them differ between the configs.
//   Dual GPS: {DUAL_FILE}
//   RS-232:   {RS232_FILE}

#ifndef ESP32_XBEE_F9P_CONFIG_DATA_H
#define ESP32_XBEE_F9P_CONFIG_DATA_H

#include <stdint.h>

typedef struct f9p_cfg_item {{
    uint32_t key;
    uint64_t value;
}} f9p_cfg_item_t;

{table('F9P_CFG_DUAL', 'Dual GPS (NAV-PVT) config, every key in file order', dual)}

{table('F9P_CFG_RS232', 'RS-232 config, only the keys that differ from F9P_CFG_DUAL', rs232_changes)}

#endif //ESP32_XBEE_F9P_CONFIG_DATA_H
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true', help='exit 1 if the header is out of date')
    args = parser.parse_args()

    header = generate()

    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != header:
            sys.exit(f'{OUTPUT.relative_to(ROOT)} is out of date, run tools/f9p_config_gen.py')
        print(f'{OUTPUT.relative_to(ROOT)} is up to date')
    else:
        OUTPUT.write_text(header)
        print(f'Wrote {OUTPUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
